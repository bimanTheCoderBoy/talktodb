"""Service to run goal calculation per candidate and update ACSSCandidateEvaluation.

After each candidate is evaluated, a comparison report (PNG + stats JSON) is
generated using the arrays already loaded by the calculator (no duplicate
UNC reads). Report paths are stored in ``result_details`` so the frontend
can present them without reading binary blobs from the database.
"""

import math
import logging
import time
from typing import List, Tuple, Dict, Any
from uuid import UUID

from fastapi import HTTPException
from redis import Redis
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy.orm.attributes import flag_modified

from asp_app.db.models import ACSSSession, ACSSStep, ACSSCandidateEvaluation, StepStatus
from asp_app.db.schemas.setup import GoalType
from asp_app.db.schemas.execution import ExecutionStepName, ExecutionStatus, ExecutionStatusState
from asp_app.services.redis_service import RedisService
from asp_app.services.run_coverage_service import RunCoverageService
from asp_app.services.calculation_services.calculation_service import CalculationService
from asp_app.services.calculation_services.base_calculation_service import RasterBestValueService
from asp_app.services.comparison.comparison_report_service import ComparisonReportService

logger = logging.getLogger(__name__)


class CandidateEvaluationService:
    """Runs the goal calculator for each unevaluated candidate and updates goal_value."""

    @staticmethod
    async def run(
        db: AsyncSession,
        session: ACSSSession,
        step: ACSSStep,
        session_id: UUID,
        goal_type: GoalType,
        goal_parameters: Dict[str, Any],
        baseline_path: str,
        candidate_paths: List[Tuple[str, str]],
        redis_client: Redis,
        job_id: str,
        execution_state_key: ExecutionStepName = ExecutionStepName.CALCULATION,
    ) -> ACSSStep:
        """
        Load ACSSCandidateEvaluation rows with status=False; for each, resolve valid
        paths from candidate_name and candidate_paths, run the goal calculator,
        generate a comparison report, then set status=True and goal_value.
        """
        step.status = StepStatus.IN_PROGRESS
        flag_modified(step, "status")
        await db.commit()

        await RunCoverageService._update_execution_state(
            db, session, execution_state_key, ExecutionStatus.RUNNING, 0, job_id, redis_client
        )

        # Defensive: drop any leftover cache from a previous task that may
        # have shared this worker process. The next session's BILs are
        # newly generated by Run Coverage for Candidates and must not be
        # served from a stale cached array.
        RasterBestValueService.clear_cache()

        try:
            result = await db.execute(
                select(ACSSCandidateEvaluation).where(
                    ACSSCandidateEvaluation.session_id == session_id,
                    ACSSCandidateEvaluation.status.is_(False),
                )
            )
            rows = list(result.scalars().all())
            total = len(rows)

            if total == 0:
                await RedisService.publish_log(redis_client,
                    f"logs:{session_id}",
                    "No unevaluated candidates; calculation step done.",
                )
                step.status = StepStatus.COMPLETED
                flag_modified(step, "status")
                await db.commit()
                await RunCoverageService._update_execution_state(
                    db, session, execution_state_key, ExecutionStatus.DONE, 100, job_id, redis_client, end_time=True
                )
                return step

            # Build iid -> path lookup {iid: path}
            iid_to_paths: Dict[str, str] = {iid: path for iid, path in candidate_paths}

            # Pre-warm the BIL cache concurrently (≤4 in flight). Each unique
            # BIL is a ~12s UNC read; without prewarm every combination would
            # re-read the same K+1 BILs (180 reads for N=10/K=2). With prewarm
            # we read each one once before the loop, and the per-combination
            # calls become cache hits. See .docs/CALCULATION_PHASE_OPTIMIZATION.md
            unique_paths: List[str] = list({baseline_path} | set(iid_to_paths.values()))
            await RedisService.publish_log(
                redis_client, f"logs:{session_id}",
                f"Pre-warming raster cache for {len(unique_paths)} unique BIL(s)…",
            )
            t_prewarm = time.perf_counter()
            await RasterBestValueService().prewarm_cache(unique_paths)
            await RedisService.publish_log(
                redis_client, f"logs:{session_id}",
                f"Raster cache pre-warmed in {time.perf_counter() - t_prewarm:.1f}s; "
                f"per-combination reads will now be cache hits.",
            )

            await RedisService.publish_log(redis_client,
                f"logs:{session_id}",
                f"Starting evaluation of {total} candidates",
            )

            # Collect manifest entries for report index
            manifest_entries: List[Dict[str, Any]] = []

            for idx, row in enumerate(rows):
                # candidate_name is "site_iid1|site_iid2|..."
                iids = set(candidate_name.strip() for candidate_name in row.candidate_name.split("|"))
                valid_paths = [iid_to_paths[iid] for iid in iids if iid in iid_to_paths.keys() and iid is not None] 

                if not valid_paths:
                    await RedisService.publish_log(redis_client,
                        f"logs:{session_id}",
                        f"Skip candidate {row.candidate_name}: no paths found",
                    )
                    continue

                await RedisService.publish_log(redis_client,
                    f"logs:{session_id}",
                    f"Evaluating candidate {row.candidate_name}: n_paths={len(valid_paths)}, baseline_path={baseline_path}, goal_type={goal_type.value}",
                )

                try:
                    # Calculator returns 4-tuple: (goal_value, kpis, baseline_array, best_array)
                    goal_value, result_details, baseline_array, best_array = (
                        await CalculationService.run_calculation_with_details(
                            goal_type=goal_type,
                            best_paths=valid_paths,
                            baseline_path=baseline_path,
                            **goal_parameters,
                        )
                    )
                except Exception as e:
                    await RedisService.publish_log(redis_client,
                        f"logs:{session_id}",
                        f"Skipped candidate {row.candidate_name}: calculation failed — {e}",
                    )
                    progress = int((idx + 1) / total * 100)
                    await RunCoverageService._update_execution_state(
                        db, session, execution_state_key, ExecutionStatus.RUNNING, progress, job_id, redis_client
                    )
                    continue

                # --- Generate comparison report (PNG + stats JSON) ---
                # Pass arrays directly — no duplicate UNC raster reads.
                report_paths: Dict[str, str] = {}
                try:
                    report_paths = await ComparisonReportService.generate_candidate_report(
                        session_id=session_id,
                        goal_type_value=goal_type.value,
                        candidate_name=row.candidate_name,
                        baseline_array=baseline_array,
                        best_array=best_array,
                        result_details=result_details or {},
                    )
                    if report_paths:
                        await RedisService.publish_log(redis_client,
                            f"logs:{session_id}",
                            f"Report generated for {row.candidate_name}: {report_paths.get('report_dir', '')}",
                        )
                except Exception as report_err:
                    logger.warning(
                        "Report generation failed for %s (non-fatal): %s",
                        row.candidate_name, report_err,
                    )
                    await RedisService.publish_log(redis_client,
                        f"logs:{session_id}",
                        f"Warning: report generation failed for {row.candidate_name}: {report_err}",
                    )

                # --- Persist goal_value + result_details (with report paths) ---
                # goal_value: float for increase_rsrp (%), 0–100 for rsrp_threshold.
                # PostgreSQL FLOAT does not accept nan/inf.
                gv = float(goal_value)
                row.goal_value = gv if math.isfinite(gv) else None

                details = dict(result_details or {})
                # Add report paths (store only strings, not binary)
                if report_paths:
                    details["Report Directory"] = report_paths.get("report_dir", "")
                    details["Report PNG"] = report_paths.get("compare_png", "")
                    details["Report Stats"] = report_paths.get("stats_json", "")
                    manifest_entries.append({
                        "candidate_name": row.candidate_name,
                        "goal_value": row.goal_value,
                        **report_paths,
                    })

                row.result_details = details
                row.status = True
                flag_modified(row, "result_details")
                await db.commit()
                await db.refresh(row)

                progress = int((idx + 1) / total * 100)
                await RunCoverageService._update_execution_state(
                    db, session, execution_state_key, ExecutionStatus.RUNNING, progress, job_id, redis_client
                )
                await RedisService.publish_log(redis_client,
                    f"logs:{session_id}",
                    f"Evaluated {row.candidate_name} -> goal_value={goal_value}",
                )

            # --- Write report manifest ---
            if manifest_entries:
                try:
                    manifest_path = await ComparisonReportService.write_manifest(
                        session_id=session_id,
                        goal_type_value=goal_type.value,
                        entries=manifest_entries,
                    )
                    if manifest_path:
                        await RedisService.publish_log(redis_client,
                            f"logs:{session_id}",
                            f"Report manifest written: {manifest_path}",
                        )
                except Exception as manifest_err:
                    logger.warning("Manifest write failed (non-fatal): %s", manifest_err)

            step.status = StepStatus.COMPLETED
            flag_modified(step, "status")
            await db.commit()
            await RunCoverageService._update_execution_state(
                db, session, execution_state_key, ExecutionStatus.DONE, 100, job_id, redis_client, end_time=True
            )
            await RedisService.publish_log(redis_client, f"logs:{session_id}", f"Calculation step done: {total} candidates evaluated")
            # Free the prewarmed BIL arrays — next session re-warms with fresh files.
            RasterBestValueService.clear_cache()
            return step

        except HTTPException:
            RasterBestValueService.clear_cache()
            raise
        except Exception as e:
            RasterBestValueService.clear_cache()
            await db.rollback()
            error_msg = str(e)
            step.status = StepStatus.FAILED
            step.step_metadata = (step.step_metadata or {}) | {"error_message": error_msg}
            flag_modified(step, "status")
            flag_modified(step, "step_metadata")
            await db.commit()
            await RunCoverageService._update_execution_state(
                db, session, execution_state_key, ExecutionStatus.ERROR, 99, job_id, redis_client, end_time=True
            )
            await RedisService.publish_log(redis_client, f"logs:{session_id}", f"Calculation step error: {error_msg}")
            raise HTTPException(status_code=400, detail=f"Calculation step failed: {error_msg}") from e
